package com.bench.wafuzzer

import org.json.JSONObject
import java.io.File

object BountyReporter {

    fun generate(reportFile: File, outFile: File): File {
        val root = JSONObject(reportFile.readText())
        val unique = root.optJSONArray("uniqueCrashes") ?: return outFile.also { it.writeText("no crashes") }
        val sb = StringBuilder()

        sb.append("# WhatsApp Android — Crash Report (auto-generated)\n\n")
        sb.append("> Generated by wa-fuzzer v3\n\n")

        sb.append("## Environment\n\n")
        sb.append("- Device: ${root.optString("device")}\n")
        sb.append("- Android: ${root.optString("android")} (SDK ${root.optInt("sdk")})\n")
        sb.append("- Report generated: ${root.optLong("generatedAt")}\n\n")

        sb.append("## Surface enumerated\n\n")
        val surface = root.optJSONArray("exportedSurface")
        if (surface != null) {
            for (i in 0 until surface.length()) {
                sb.append("- `").append(surface.getString(i)).append("`\n")
            }
        }
        sb.append("\n")

        for (i in 0 until unique.length()) {
            val c = unique.getJSONObject(i)
            sb.append("---\n\n")
            sb.append("## Finding ${i + 1}: ${c.optString("signal")} — `")
                .append(c.optString("activity").substringAfterLast('.'))
                .append("`\n\n")

            sb.append("**Package:** `").append(c.optString("pkg")).append("`\n\n")
            sb.append("**Component:** `").append(c.optString("activity")).append("`\n\n")
            sb.append("**Signal:** `").append(c.optString("signal")).append("`\n\n")

            val crashed = c.optString("crashedProcess", "")
            if (crashed.isNotBlank()) {
                sb.append("**Crashed process:** `").append(crashed).append("`\n\n")
            }

            val ex = c.optString("exception", "")
            if (ex.isNotBlank()) {
                sb.append("**Exception:**\n\n```\n").append(ex).append("\n```\n\n")
            }

            sb.append("### Steps to reproduce\n\n")
            sb.append("1. Install target WhatsApp build on a clean device.\n")
            sb.append("2. Launch WhatsApp once, log in with a test account, then close the app.\n")
            sb.append("3. From the wa-fuzzer app, send the following intent:\n\n")
            sb.append("```kotlin\n")
            sb.append("Intent(").append(c.optString("action")).append(").apply {\n")
            sb.append("    setPackage(\"").append(c.optString("pkg")).append("\")\n")
            val uri = c.optString("dataUri", "")
            if (uri.isNotBlank()) {
                sb.append("    data = Uri.parse(\"").append(uri.replace("\"", "\\\"")).append("\")\n")
            }
            val mime = c.optString("mimeType", "")
            if (mime.isNotBlank()) {
                sb.append("    type = \"").append(mime.replace("\"", "\\\"")).append("\"\n")
            }
            sb.append("    addCategory(Intent.CATEGORY_DEFAULT)\n")
            sb.append("    flags = Intent.FLAG_ACTIVITY_NEW_TASK\n")
            sb.append("}\n")
            sb.append("startActivity(intent)\n")
            sb.append("```\n\n")
            sb.append("4. Observe process death / crash in logcat.\n\n")
            sb.append("### Expected\n\nIntent handled gracefully without process termination.\n\n")
            sb.append("### Actual\n\nProcess `").append(crashed.ifBlank { "com.whatsapp" }).append("` terminated.\n\n")
        }

        outFile.writeText(sb.toString())
        return outFile
    }
}
